"""Pre-written spoken cues (TRI §6.5): 3 variants per cue id, voiced once, picked without repeats.

cues.json maps id → [{"text", "file"}]; MP3s live in DATA_DIR/cues/mp3/<cue_id>_<n>.mp3 (served at /audio/).
DATA_DIR/cues/cues.json wins over the hand-written default committed at <repo>/data/cues/cues.json.

    python -m server.ai.cue_library --generate-text    # one batched Gemini request (FAST model)
    python -m server.ai.cue_library --generate-audio   # ElevenLabs for missing MP3s only

FIXED_CUES (safety) and SCRIPTED_CUES (the LCD trainer's lines) are hand-written: never sent to Gemini.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import random
import re
from collections import deque
from pathlib import Path
from typing import Any

from pydantic import RootModel

from server.ai import eleven, gemini
from server.ai.prompts import load_prompt
from server.ai.validators import parse_json, validate_text
from server.config import REPO_ROOT, cfg
from server.logging_setup import get_logger

log = get_logger("ai.cues")

VARIANTS = 3
HISTORY = 2  # a pick never repeats one of the last 2 variants played for that cue

# Cue id → what the line must say (the brief for Gemini).
CUE_IDS: dict[str, str] = {
    "set_start": "start of a set: begin slowly",
    "knees_out": "push your knees out over your toes",
    "knee_cave_l": "left knee is caving in: push the left knee out",
    "knee_cave_r": "right knee is caving in: push the right knee out",
    "trunk_lean": "leaning forward too much: keep your chest up",
    "depth_more": "squat a little deeper if comfortable",
    "slow_down": "move more slowly and with control",
    "good_rep": "praise for a good repetition",
    "encouragement": "general encouragement during the set",
    "countdown_3": "the number three",
    "countdown_2": "the number two",
    "countdown_1": "the number one",
    "rest": "rest now and breathe",
    "set_done": "the set is finished, well done",
    "pause": "the session is paused",
    "resume": "resuming the session",
    "fatigue": "you seem tired, take it easy",
    "rest_extended": "take a longer rest before the next set",
    "greeting_generic": "a friendly hello, invite them to raise their hand when ready",
}

# Safety lines are hand-written and never regenerated by AI (the safety path never uses AI).
FIXED_CUES: dict[str, list[str]] = {
    "check_in": ["Are you okay? Raise your hand to let me know."],
    "im_ok_thanks": ["Thanks for letting me know you're okay."],
}

_NUMBER_WORDS = ("One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten", "Eleven",
                 "Twelve", "Thirteen", "Fourteen", "Fifteen", "Sixteen", "Seventeen", "Eighteen", "Nineteen",
                 "Twenty")

# The LCD trainer voice's lines (TrainerVoice agent): hand-written, voiced once, never regenerated by AI.
SCRIPTED_CUES: dict[str, list[str]] = {
    "instructions": ["Stand back so I can see you from head to toe. When you're ready, raise your hand and "
                     "we'll begin."],
    "raise_hand": ["Raise your hand when you're ready to start!",
                   "Whenever you're ready, just raise your hand!",
                   "Ready? Raise your hand and we'll begin!"],
    "lets_go": ["Perfect! Let's get started.", "Great, here we go!", "Awesome! Let's do this."],
    **{f"count_{n}": [f"{word}!"] for n, word in enumerate(_NUMBER_WORDS, start=1)},
    "halfway": ["Halfway there, you're doing great!", "You're halfway, keep it up!"],
    "last_rep": ["Last one, make it count!", "One more, you've got this!"],
    "session_done": ["That's your whole session. Amazing work today!",
                     "All done for today. You did amazing!"],
    "calling_contact": ["I'm calling your emergency contact now. Stay still, help is on the way."],
    "contact_on_call": ["Your emergency contact is on the line. I'm staying right here with you."],
    "call_failed": ["I couldn't reach your contact. If anyone is nearby, please call 911."],
}

# Hand-written cue ids: kept out of the Gemini request and written as-is.
HAND_WRITTEN: dict[str, list[str]] = {**FIXED_CUES, **SCRIPTED_CUES}

DEFAULT_PATH = REPO_ROOT / "data" / "cues" / "cues.json"

# Cue ids become MP3 file names served from /audio: plain names only, never a path.
_SAFE_NAME_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
_SAFE_FILE_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}\.mp3$")


def cues_path() -> Path:
    return Path(cfg.DATA_DIR) / "cues" / "cues.json"


def mp3_dir() -> Path:
    return Path(cfg.DATA_DIR) / "cues" / "mp3"


def rule_cue_ids(rules_dir: Path | None = None) -> dict[str, str]:
    """Cue ids from Eric's data/rules/*.json: objects with an "id", top-level, in a list, or under "rules"."""
    found: dict[str, str] = {}
    directory = rules_dir or Path(cfg.DATA_DIR) / "rules"
    for path in sorted(directory.glob("*.json")) if directory.is_dir() else []:
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            log.warning("unreadable rules file", extra={"path": str(path)})
            continue
        items = data.get("rules", [data]) if isinstance(data, dict) else data
        for item in items if isinstance(items, list) else []:
            if isinstance(item, dict) and isinstance(item.get("id"), str) and _SAFE_NAME_RE.match(item["id"]):
                desc = item.get("cue") or item.get("message") or item.get("description") or item["id"]
                found[item["id"]] = str(desc)
    return found


def all_cue_ids() -> dict[str, str]:
    return {**CUE_IDS, **{k: v for k, v in rule_cue_ids().items() if k not in HAND_WRITTEN}}


class CueLibrary:
    def __init__(self, entries: dict[str, list[dict[str, str]]], audio_root: Path,
                 rng: random.Random | None = None) -> None:
        self.entries = entries
        self.audio_root = audio_root
        self.rng = rng or random.Random()
        self._history: dict[str, deque[int]] = {}
        self._voiced: set[str] = set()
        self.refresh_audio()

    @classmethod
    def load(cls, path: Path | None = None, rng: random.Random | None = None) -> CueLibrary:
        source = path or (cues_path() if cues_path().is_file() else DEFAULT_PATH)
        try:
            entries = json.loads(source.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            log.warning("cue library unreadable, using fixed lines only", extra={"path": str(source)})
            entries = {}
        entries = _clean_entries(entries, source)
        for cue_id, lines in HAND_WRITTEN.items():
            entries.setdefault(cue_id, [{"text": t, "file": f"{cue_id}_{i + 1}.mp3"} for i, t in enumerate(lines)])
        return cls(entries, mp3_dir(), rng)

    def refresh_audio(self) -> None:
        """Re-scan which variant MP3s exist (after --generate-audio)."""
        self._voiced = {f.name for f in self.audio_root.glob("*.mp3")} if self.audio_root.is_dir() else set()

    def pick(self, cue_id: str) -> dict[str, Any] | None:
        """{id, text, audio_url} for a variant not among the last 2 played; None for an unknown id."""
        variants = self.entries.get(cue_id)
        if not variants:
            return None
        history = self._history.setdefault(cue_id, deque(maxlen=HISTORY))
        recent = list(history)[-(len(variants) - 1):] if len(variants) > 1 else []
        choices = [i for i in range(len(variants)) if i not in recent]
        index = self.rng.choice(choices)
        history.append(index)
        variant = variants[index]
        file = variant.get("file")
        return {"id": cue_id, "text": variant["text"],
                "audio_url": f"/audio/{file}" if file and file in self._voiced else None}


def _clean_entries(raw: Any, source: Path) -> dict[str, list[dict[str, str]]]:
    """Keep well-formed variants only: a text, and a plain .mp3 file name (or none)."""
    entries: dict[str, list[dict[str, str]]] = {}
    if not isinstance(raw, dict):
        log.warning("cue library is not an object, ignoring it", extra={"path": str(source)})
        return entries
    for cue_id, lines in raw.items():
        if not isinstance(cue_id, str) or not _SAFE_NAME_RE.match(cue_id) or not isinstance(lines, list):
            continue
        kept = [{"text": e["text"], **({"file": e["file"]} if isinstance(e.get("file"), str)
                                       and _SAFE_FILE_RE.match(e["file"]) else {})}
                for e in lines if isinstance(e, dict) and isinstance(e.get("text"), str) and e["text"].strip()]
        if kept:
            entries[cue_id] = kept
    return entries


_library: CueLibrary | None = None


def library() -> CueLibrary:
    global _library
    if _library is None:
        _library = CueLibrary.load()
    return _library


def reload() -> CueLibrary:
    global _library
    _library = CueLibrary.load()
    return _library


def pick(cue_id: str) -> dict[str, Any] | None:
    return library().pick(cue_id)


def enrich_cue_event(msg: dict[str, Any]) -> None:
    """Bridge event enricher: give every `cue {id}` event its caption `text` and `audio_url` (TRI §6.5).

    The library variant wins; an id the library does not know keeps what the engine sent.
    """
    if msg.get("type") != "cue":
        return
    cue_id = msg.get("id")
    picked = pick(cue_id) if isinstance(cue_id, str) else None
    if picked is not None:
        msg["text"], msg["audio_url"] = picked["text"], picked["audio_url"]
    msg.setdefault("text", None)
    msg.setdefault("audio_url", None)


class _Variants(RootModel[dict[str, list[str]]]):
    pass


async def generate_text() -> dict[str, list[dict[str, str]]]:
    """One batched FAST-model request for every AI-written cue id → DATA_DIR/cues/cues.json.

    Variants that fail validation are dropped; an id with no valid variant keeps its current lines.
    A changed line deletes its old MP3 so --generate-audio voices it again.
    """
    ids = all_cue_ids()
    reply = await gemini.ask("cue_library", gemini.models.fast(), load_prompt("cues"),
                             [{"role": "user", "content": "DATA:\n" + json.dumps(ids, indent=1)}],
                             timeout_s=60.0, json_mode=True)
    parsed = parse_json(reply.text, _Variants)
    if parsed is None:
        raise gemini.AIUnavailable("cue library answer was not the expected JSON")
    current = CueLibrary.load().entries
    out: dict[str, list[dict[str, str]]] = {}
    for cue_id in ids:
        texts: list[str] = []
        for raw in parsed.root.get(cue_id, []):
            text = validate_text(raw, "cue", [])
            if text and text not in texts:
                texts.append(text)
        if not texts:
            log.warning("no valid generated variant, keeping current lines", extra={"cue_id": cue_id})
            out[cue_id] = current.get(cue_id, [])
            continue
        out[cue_id] = []
        for n, text in enumerate(texts[:VARIANTS], start=1):
            entry = {"text": text, "file": f"{cue_id}_{n}.mp3"}
            old = next((e for e in current.get(cue_id, []) if e.get("file") == entry["file"]), None)
            if old is not None and old.get("text") != text:
                (mp3_dir() / entry["file"]).unlink(missing_ok=True)
            out[cue_id].append(entry)
    for cue_id, lines in HAND_WRITTEN.items():
        out[cue_id] = [{"text": t, "file": f"{cue_id}_{i + 1}.mp3"} for i, t in enumerate(lines)]
    _write_json(cues_path(), out)
    return out


async def generate_audio() -> dict[str, int]:
    """Voice every variant whose MP3 is missing (scripted lines included). Existing files cost nothing.

    Offline CLI only: passes force=True past the ELEVEN_RUNTIME_TTS gate.
    """
    lib = CueLibrary.load()
    lib.refresh_audio()
    done = failed = chars = 0
    for lines in lib.entries.values():
        for entry in lines:
            if "file" not in entry:
                continue
            dest = mp3_dir() / entry["file"]
            if dest.is_file():
                continue
            if await eleven.synthesize_to(entry["text"], dest, force=True):
                done += 1
                chars += len(entry["text"])
            else:
                failed += 1
    reload()
    return {"generated": done, "failed": failed, "chars": chars}


def missing_audio_chars() -> int:
    lib = CueLibrary.load()
    return sum(len(e["text"]) for lines in lib.entries.values() for e in lines
               if "file" in e and not (mp3_dir() / e["file"]).is_file())


def _write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--generate-text", action="store_true", help="one Gemini request → cues.json")
    group.add_argument("--generate-audio", action="store_true", help="ElevenLabs for missing MP3s")
    args = parser.parse_args()
    if args.generate_text:
        out = asyncio.run(generate_text())
        print(f"wrote {cues_path()} with {len(out)} cue ids")
    else:
        print(f"{missing_audio_chars()} characters to voice")
        print(asyncio.run(generate_audio()))


if __name__ == "__main__":
    main()
